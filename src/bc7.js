function decodeBlock(data, off, out) {
  let bitPos = 0;
  const getBits = (n) => {
    let v = 0;
    for (let i = 0; i < n; i++) { const b = (data[off + (bitPos >> 3)] >> (bitPos & 7)) & 1; v |= b << i; bitPos++; }
    return v;
  };
  let mode = 0;
  while (mode < 8 && !getBits(1)) mode++;
  if (mode === 8) { for (let i = 0; i < 16; i++) { out[i * 4] = out[i * 4 + 1] = out[i * 4 + 2] = out[i * 4 + 3] = 0; } return; }
  const [subsets, partBits, rotBits, idxSelBits, cb, ab, pMode, ib, ib2] = MODES[mode];
  const part = partBits ? getBits(partBits) : 0;
  const rot = rotBits ? getBits(rotBits) : 0;
  const idxSel = idxSelBits ? getBits(1) : 0;
  const nEp = subsets * 2;
  const ep = Array.from({ length: nEp }, () => [0, 0, 0, 255]);
  for (let ch = 0; ch < 3; ch++) for (let e = 0; e < nEp; e++) ep[e][ch] = getBits(cb);
  if (ab) for (let e = 0; e < nEp; e++) ep[e][3] = getBits(ab);
  let pbits = [];
  if (pMode === 1) for (let e = 0; e < nEp; e++) pbits.push(getBits(1));
  if (pMode === 2) { for (let s = 0; s < subsets; s++) { const p = getBits(1); pbits.push(p, p); } }
  const expand = (v, bits, p) => {
    let b = bits;
    if (pMode) { v = (v << 1) | p; b++; }
    v = v << (8 - b);
    return v | (v >> b);
  };
  for (let e = 0; e < nEp; e++) {
    const p = pMode ? pbits[e] : 0;
    for (let ch = 0; ch < 3; ch++) ep[e][ch] = expand(ep[e][ch], cb, p);
    if (ab) ep[e][3] = expand(ep[e][3], ab, p);
  }
  const partTable = subsets === 3 ? P3[part] : subsets === 2 ? P2[part] : null;
  const anchor = (s) => s === 0 ? 0 : subsets === 2 ? A2[part] : (s === 1 ? A3a[part] : A3b[part]);
  const idx = new Array(16), idx2 = new Array(16);
  for (let i = 0; i < 16; i++) {
    const s = partTable ? partTable[i] : 0;
    idx[i] = getBits(i === anchor(s) ? ib - 1 : ib);
  }
  if (ib2) for (let i = 0; i < 16; i++) idx2[i] = getBits(i === 0 ? ib2 - 1 : ib2);
  const wt = (b) => b === 2 ? W2 : b === 3 ? W3 : W4;
  for (let i = 0; i < 16; i++) {
    const s = partTable ? partTable[i] : 0;
    const a = ep[s * 2], b = ep[s * 2 + 1];
    let ci = idx[i], ai = idx[i], cw = wt(ib), aw = wt(ib);
    if (ib2) { if (idxSel) { ci = idx2[i]; cw = wt(ib2); } else { ai = idx2[i]; aw = wt(ib2); } }
    const lerp = (x, y, w) => (x * (64 - w) + y * w + 32) >> 6;
    let r = lerp(a[0], b[0], cw[ci]), g = lerp(a[1], b[1], cw[ci]), bl = lerp(a[2], b[2], cw[ci]);
    let al = ab ? lerp(a[3], b[3], aw[ai]) : 255;
    if (rot === 1) [r, al] = [al, r]; else if (rot === 2) [g, al] = [al, g]; else if (rot === 3) [bl, al] = [al, bl];
    out[i * 4] = r; out[i * 4 + 1] = g; out[i * 4 + 2] = bl; out[i * 4 + 3] = al;
  }
}

function decodeBC7(data, w, h) {
  const out = Buffer.alloc(w * h * 4);
  const blk = new Uint8Array(64);
  const bw = Math.ceil(w / 4), bh = Math.ceil(h / 4);
  let off = 0;
  for (let by = 0; by < bh; by++) for (let bx = 0; bx < bw; bx++, off += 16) {
    decodeBlock(data, off, blk);
    for (let k = 0; k < 16; k++) {
      const x = bx * 4 + (k & 3), y = by * 4 + (k >> 2);
      if (x >= w || y >= h) continue;
      const o = (y * w + x) * 4;
      out[o] = blk[k * 4]; out[o + 1] = blk[k * 4 + 1]; out[o + 2] = blk[k * 4 + 2]; out[o + 3] = blk[k * 4 + 3];
    }
  }
  return out;
}

